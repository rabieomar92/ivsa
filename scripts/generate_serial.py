Import("env")

import json
import secrets
from pathlib import Path
from SCons.Script import COMMAND_LINE_TARGETS

project_dir = Path(env["PROJECT_DIR"])
header_path = project_dir / "include" / "build_identity.h"
registry_path = project_dir / "scripts" / "serial_registry.json"


def allocate_serial():
    try:
        registry = json.loads(registry_path.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        registry = {"used": []}

    used = {str(value) for value in registry.get("used", [])}
    used_suffixes = {
        value.rsplit("-", 1)[-1]
        for value in used
        if len(value.rsplit("-", 1)[-1]) == 12
        and value.rsplit("-", 1)[-1].isdigit()
    }
    if len(used_suffixes) >= 1_000_000_000_000:
        raise RuntimeError("All serials in the VS-2607-12-############ namespace have been allocated.")

    while True:
        suffix = f"{secrets.randbelow(1_000_000_000_000):012d}"
        serial = f"VS-2607-12-{suffix}"
        if suffix not in used_suffixes:
            break

    registry["used"] = sorted((*used, serial))
    registry["last"] = serial
    registry_temp = registry_path.with_suffix(".json.tmp")
    header_temp = header_path.with_suffix(".h.tmp")
    registry_temp.write_text(json.dumps(registry, indent=2) + "\n", encoding="utf-8")
    header_temp.write_text(
        "#pragma once\n"
        "// Generated by scripts/generate_serial.py. Do not edit manually.\n"
        f'#define VIBSCOPE_BUILD_SUFFIX "{suffix}"\n'
        f'#define VIBSCOPE_BUILD_SERIAL "{serial}"\n',
        encoding="utf-8",
    )
    registry_temp.replace(registry_path)
    header_temp.replace(header_path)
    print(f"[identity] Allocated firmware serial {serial}")


# Ordinary builds reuse the current identity so compiling and testing do not
# consume serials. Every firmware upload provisions a fresh identity as required.
upload_requested = "upload" in COMMAND_LINE_TARGETS
if upload_requested or not header_path.exists():
    allocate_serial()
else:
    print("[identity] Reusing current firmware serial for a non-upload build.")
